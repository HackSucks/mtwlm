#!/bin/sh
#
# syntax-check.sh -- build every translation unit of AirportMtwlm to a
# Mach-O object with a stock (non-Apple) clang, on a Linux host.
#
# The kext itself can only be linked on macOS against Kernel.framework,
# but this catches the vast majority of porting mistakes: missing
# headers, undeclared identifiers, wrong signatures, and duplicate or
# unresolved symbols between translation units.
#
#   ./scripts/syntax-check.sh              classic variant
#   ./scripts/syntax-check.sh V2=1         Sonoma+ variant
#   ./scripts/syntax-check.sh OSVER=13     classic, Ventura API level
#   ./scripts/syntax-check.sh --keep       keep the object directory
#
# Requirements: clang, llvm-nm, MacKernelSDK at ../MacKernelSDK.
#
set -eu

cd "$(dirname "$0")/.."

keep=0
args=""
for a in "$@"; do
    case "$a" in
        --keep) keep=1 ;;
        *) args="$args $a" ;;
    esac
done

# Makefile variables are parsed here (make does not need xcrun for the
# print-* targets), so the flags can never drift from the real build.
mkvar() {
    make -s -f Makefile $args print-"$1"
}

cxxflags=$(mkvar cxxflags)
cflags=$(mkvar cflags)
srcs=$(mkvar srcs)
infoplist=$(mkvar infoplist)

# xcrun -sdk macosx clang++ -> clang
flags=$(echo "$cxxflags" | sed 's/^xcrun -sdk macosx clang++//')
flags_c=$(echo "$cflags" | sed 's/^xcrun -sdk macosx clang//')

objdir=/tmp/mtwlm-syntax
rm -rf "$objdir"
mkdir -p "$objdir"

CC=${CC:-clang}
fail=0
n=0
for f in $srcs; do
    n=$((n + 1))
    o="$objdir/$(echo "$f" | tr '/' '_' | sed 's/\.\(c\|cpp\)$/.o/')"
    # kmod_info.c must be C: it defines the unmangled _kmod_info and
    # needs C linkage for _start/_stop (see the Makefile rule).
    case "$f" in
        kmod_info.c)
            lang=c
            fflags=$flags_c
            ;;
        *)
            lang=c++
            fflags=$flags
            ;;
    esac
    if ! $CC $fflags -x $lang -O0 -c "$f" -o "$o" 2>"$objdir/err"; then
        echo "### $f"
        grep -E 'error:' "$objdir/err" | head -5
        fail=$((fail + 1))
    fi
done

echo "compiled $n translation units, $fail failed"

if [ "$fail" -ne 0 ]; then
    exit 1
fi

# Cross-TU symbol sanity: no duplicate definitions, nothing that looks
# like our own code left undefined (kernel KPI symbols are expected).
python3 - "$objdir" <<'PY'
import collections, glob, subprocess, sys

objdir = sys.argv[1]
defined = collections.defaultdict(list)
undef = set()
for o in glob.glob(objdir + '/*.o'):
    out = subprocess.run(['llvm-nm', '-g', '--format=posix', o],
                         capture_output=True, text=True).stdout
    for line in out.splitlines():
        p = line.split()
        if len(p) < 2:
            continue
        if p[1] == 'U':
            undef.add(p[0])
        elif p[1] in ('T', 'D', 'B', 'S', 'R', 'C', 'W', 'V'):
            defined[p[0]].append(o)

dups = {k: v for k, v in defined.items() if len(v) > 1}
missing = sorted(s for s in undef if s not in defined)
internal = [s for s in missing if s.startswith(
    ('_mwx_', '_mt79', '_ieee80211_', '_loadfirmware', '_airport_'))
    or 'Mtwlm' in s or 'ItlMwx' in s]

print('defined symbols:', len(defined))
print('unresolved symbols:', len(missing), '(kernel/IOKit KPIs expected)')
print('duplicate definitions:', len(dups))
if internal:
    print('internal symbols left unresolved:', internal)
for k, v in list(dups.items())[:10]:
    print('  duplicate:', k, v)
sys.exit(1 if dups or internal else 0)
PY

# The plist is generated by hand (no Xcode variable substitution), so
# validate it too.
python3 - "$infoplist" <<'PY'
import plistlib, sys
d = plistlib.load(open(sys.argv[1], 'rb'))
assert d['CFBundleIdentifier'], 'missing CFBundleIdentifier'
pers = d['IOKitPersonalities']
print('plist ok:', sys.argv[1], '->', ', '.join(sorted(pers)))
PY

if [ "$keep" -eq 0 ]; then
    rm -rf "$objdir"
fi
